HUUDAS: tuple[Huudas, ...] = (
    GAN35 + GAN110P + GAN110U + GAN220 + GAN330 + GAN500 + GANHOYD + JB35 + SHILJ
)


def katalog() -> Katalog:
    """Ачаалсан каталог (`tulguuruud.json` байвал түүний утга давамгайлна)."""
    return load(HUUDAS)


def main() -> int:
    """Хүснэгтийн тойм хэвлэнэ. `--json` өгвөл `tulguuruud.json`-г бичнэ."""
    from tulguursan import write_json

    k = katalog()
    print(f"Каталог: {len(k)} тулгуур, {len(k.huudas)} хуудас\n")
    print(f"{'кВ':>5} {'нийт':>5} {'ган':>5} {'ЖБ':>4} {'баталгаатай':>12}")
    for kv in k.hutseluud():
        bag = k.shuult(hutsel=kv)
        gan = sum(1 for t in bag if t.material == GAN)
        jb = sum(1 for t in bag if t.material == JB)
        bat = sum(1 for t in bag if t.batalgaa)
        print(f"{kv:>5} {len(bag):>5} {gan:>5} {jb:>4} {bat:>12}")
    buh = k.buh
    print(f"\nНийт: {len(buh)}, хэмжээс баталгаатай: {sum(1 for t in buh if t.batalgaa)}")
    if "--json" in sys.argv:
        print(f"JSON: {write_json(k)}")
    else:
        print("Хэмжээсийг засах JSON гаргах бол: --json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
