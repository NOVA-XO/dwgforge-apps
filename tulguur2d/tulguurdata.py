# --------------------------------------------------------------------------
# Траверсын байрлалын хэв маяг
# --------------------------------------------------------------------------


def bochka(dood: float, a: float, b: float, dz: float = 4.0) -> tuple[tuple[float, float, float], ...]:
    """Нэг цепийн гурвалжин ("бочка") байрлал: доор 2 фаз, дээр 1 фаз."""
    return ((dood, a, b), (dood + dz, a, 0.0))


def hos(dood: float, arms: tuple[float, ...], dz: float = 4.0) -> tuple[tuple[float, float, float], ...]:
    """Хоёр цепийн байрлал: түвшин бүрт хоёр тал тэнцүү гартай."""
    return tuple((dood + i * dz, a, a) for i, a in enumerate(arms))


def hevtee(z: float, a: float) -> tuple[tuple[float, float, float], ...]:
    """Хэвтээ байрлал: 3 фаз нэг траверс дээр (тэнхлэг дээр нэг, хажуу тийш хоёр)."""
    return ((z, a, a),)


def negtor(z: float, a: float) -> tuple[tuple[float, float, float], ...]:
    """Ганц траверс, хоёр тал тэнцүү."""
    return ((z, a, a),)


